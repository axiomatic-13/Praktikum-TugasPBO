public class ManipulasiString {
    String a;
    String b;

    // Method ubah string a ke huruf kecil
    public String ubahKeLowercase() {
        return a.toLowerCase();
    }

    // Method ubah string b ke huruf besar
    public String ubahKeUppercase() {
        return b.toUpperCase();
    }
}
